#!/bin/bash
set -euo pipefail

# Only publish client IDs. OAuth secrets must never enter env.js or startup logs.
declare -A oauth_ids=()
IFS=';' read -ra oauth_parts <<< "${EX_ConnectionStrings__OAuth:-}"
for part in "${oauth_parts[@]}"; do
    key="${part%%=*}"
    key="${key//[[:space:]]/}"
    value="${part#*=}"
    value="${value#"${value%%[![:space:]]*}"}"
    value="${value%"${value##*[![:space:]]}"}"
    case "$key" in
        GitHubId|GoogleId|IntercomId|MicrosoftId|SlackId)
            oauth_ids[$key]="$value" ;;
    esac
done

js_string() {
    local value="${1:-}"
    value="${value//\\/\\\\}"
    value="${value//\'/\\\'}"
    value="${value//$'\r'/\\r}"
    value="${value//$'\n'/\\n}"
    printf "'%s'" "$value"
}

write_setting() {
    printf '    %s: ' "$1"
    js_string "$2"
    printf ',\n'
}

mkdir -p _app
{
    printf 'export const env={\n    PUBLIC_BASE_URL: '
    js_string "${EX_ApiUrl:-}"
    printf ' || window.location.origin,\n'
    write_setting PUBLIC_ENABLE_ACCOUNT_CREATION "${EX_EnableAccountCreation:-true}"
    write_setting PUBLIC_ENABLE_SSL "${EX_EnableSsl:-false}"
    write_setting PUBLIC_SYSTEM_NOTIFICATION_MESSAGE "${EX_NotificationMessage:-}"
    write_setting PUBLIC_EXCEPTIONLESS_API_KEY "${EX_ExceptionlessApiKey:-}"
    write_setting PUBLIC_EXCEPTIONLESS_CLIENT_SETUP_SHOW_SERVER_URL "${EX_ClientSetupShowServerUrl:-true}"
    write_setting PUBLIC_EXCEPTIONLESS_SERVER_URL "${EX_ExceptionlessServerUrl:-}"
    write_setting PUBLIC_STRIPE_PUBLISHABLE_KEY "${EX_StripePublishableApiKey:-}"
    write_setting PUBLIC_GITHUB_APPID "${oauth_ids[GitHubId]:-}"
    write_setting PUBLIC_GOOGLE_APPID "${oauth_ids[GoogleId]:-}"
    write_setting PUBLIC_MICROSOFT_APPID "${oauth_ids[MicrosoftId]:-}"
    write_setting PUBLIC_INTERCOM_APPID "${oauth_ids[IntercomId]:-}"
    write_setting PUBLIC_SLACK_APPID "${oauth_ids[SlackId]:-}"
    printf '};\n'
} > _app/env.js

checksum=$(md5sum _app/env.js | cut -c 1-32)
version_env_import="s|/_app/env\.js(\\?v=[a-f0-9]+)?|/_app/env.js?v=$checksum|g"
sed -E -i "$version_env_import" index.html

# Under strict-dynamic, Chromium can block imports from SvelteKit's parser-inserted
# bootstrap. Run the same code from a dynamically inserted script in the same container.
spa_html=$(cat index.html)
if [[ "$spa_html" == *"script-src "* ]]; then
    loader_tag='<script data-sveltekit-bootstrap-loader>'
    bootstrap_tag='<script>'
    if [[ "$spa_html" == *"$loader_tag"* ]]; then
        bootstrap_tag=$loader_tag
    fi
    bootstrap_tail=${spa_html#*"$bootstrap_tag"}
    if [[ "$bootstrap_tail" == "$spa_html" || "$bootstrap_tail" == *"$bootstrap_tag"* || "$bootstrap_tail" != *'</script>'* ]]; then
        printf 'Expected one Svelte bootstrap script\n' >&2
        exit 1
    fi
    if [[ "$bootstrap_tag" == "$loader_tag" ]]; then
        sed -E -i "$version_env_import" _app/bootstrap.js
    else
        printf '%s' "${bootstrap_tail%%'</script>'*}" > _app/bootstrap.js
    fi
    bootstrap_version=$(sha256sum _app/bootstrap.js | cut -c 1-64)
    bootstrap_integrity=$(openssl dgst -sha256 -binary _app/bootstrap.js | openssl base64 -A)

    # Hash the loader for CSP, and bind the external script to the generated bytes with SRI.
    loader=$(cat <<EOF
{
    const script = document.createElement('script');
    script.src = '/_app/bootstrap.js?v=$bootstrap_version';
    script.integrity = "sha256-$bootstrap_integrity";
    document.currentScript.after(script);
}
EOF
)
    loader_hash=$(printf '%s' "$loader" | openssl dgst -sha256 -binary | openssl base64 -A)
    script_policy=${spa_html#*script-src }
    script_policy=${script_policy%%;*}
    old_hash=$(printf '%s' "$script_policy" | grep -oE "'sha256-[A-Za-z0-9+/]{43}='")
    if [[ "$old_hash" == *$'\n'* ]]; then
        printf 'Expected one Svelte bootstrap hash\n' >&2
        exit 1
    fi
    head=${spa_html%%"$bootstrap_tag"*}
    tail=${bootstrap_tail#*'</script>'}
    printf '%s%s%s</script>%s\n' "${head/"$old_hash"/"'sha256-$loader_hash'"}" "$loader_tag" "$loader" "$tail" > index.html
fi
